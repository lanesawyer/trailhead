//! The sandbox's tool environment (`docs/factory/sandbox.md`): the repo's `[stack]` tools become a mise config,
//! installed with `mise bootstrap`. mise is an implementation detail; nothing here is visible to the repo.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Stdio;

use tokio::process::Command;
use trailhead_factory::{Error, InstallHost, Result};

/// The only parts of `mise bootstrap` the factory runs. An allowlist, so a part a later mise adds isn't picked up by
/// surprise. The rest (firewall, accounts, user, systemd units, services, dotfiles, remote) fight the sandbox: the
/// factory owns egress and the daemon's user.
pub const BOOTSTRAP_PARTS: &str = "packages,tools,task";

/// Where the repo's own mise config may live, in mise's order of precedence.
const REPO_CONFIGS: &[&str] = &[
    "mise.local.toml",
    "mise.toml",
    ".mise.toml",
    "mise/config.toml",
    ".config/mise.toml",
    ".config/mise/config.toml",
];

/// The generated config's file name in mise's global `conf.d`. Global config has the lowest precedence, so a pin in
/// the repo's own `mise.toml` wins over the factory's tool of the same name.
const GENERATED: &str = "trailhead-factory.toml";

/// The mise config for the factory's tools.
pub fn render(tools: &BTreeMap<String, String>) -> String {
    let mut table = toml::Table::new();
    let tools = tools.iter().map(|(k, v)| (k.clone(), toml::Value::String(v.clone()))).collect();
    table.insert("tools".into(), toml::Value::Table(tools));
    format!("# Generated by trailhead-factory from [stack] in factory.toml.\n{table}")
}

/// The tools the repo's own `mise.toml` already pins, among `tools`: those keep the repo's version.
pub fn overridden(tools: &BTreeMap<String, String>, repo_config: &str) -> Vec<String> {
    let Ok(parsed) = repo_config.parse::<toml::Table>() else { return Vec::new() };
    let Some(pinned) = parsed.get("tools").and_then(|t| t.as_table()) else { return Vec::new() };
    tools.keys().filter(|k| pinned.contains_key(*k)).cloned().collect()
}

const GITHUB: &[&str] =
    &["github.com", "api.github.com", "objects.githubusercontent.com", "release-assets.githubusercontent.com"];
const PYPI: &[&str] = &["pypi.org", "files.pythonhosted.org"];
const MISE_VERSIONS: &[&str] = &["mise.jdx.dev", "mise-versions.jdx.dev"];

/// The hosts installing a mise tool needs, by tool or backend (`docs/factory/sandbox.md`): the one table, so what a
/// sandbox opens for an install is reviewable in one place. `None` for a tool it doesn't know, which is never guessed.
/// `tool` is a mise tool key: a name (`node`) or `backend:name` (`npm:prettier`, `core:node`).
pub fn hosts_for(tool: &str) -> Option<Vec<&'static str>> {
    let (backend, name) = match tool.split_once(':') {
        Some(("core", name)) => ("", name),
        Some((backend, _)) => (backend, ""),
        None => ("", tool),
    };
    let hosts: &[&[&str]] = match (backend, name) {
        ("npm", _) => &[&["registry.npmjs.org"]],
        ("pipx" | "pypi", _) => &[PYPI],
        ("github" | "aqua" | "ubi", _) => &[GITHUB],
        ("", "node") => &[&["nodejs.org"]],
        ("", "rust") => &[&["static.rust-lang.org"]],
        ("", "go") => &[&["go.dev", "dl.google.com"]],
        // Prebuilt interpreters are GitHub release assets; pip comes from PyPI.
        ("", "python") => &[GITHUB, PYPI],
        // aqua's registry fetches pnpm from its GitHub releases.
        ("", "pnpm") => &[GITHUB],
        _ => return None,
    };
    Some(hosts.concat())
}

/// The tools in the repo's own mise configs, which `mise bootstrap` installs from the checkout at `dir`.
fn repo_tools(dir: &Path) -> Vec<String> {
    let mut tools = Vec::new();
    for path in REPO_CONFIGS.iter().map(|c| dir.join(c)).filter(|p| p.exists()) {
        let Ok(text) = std::fs::read_to_string(&path) else { continue };
        let Ok(parsed) = text.parse::<toml::Table>() else { continue };
        if let Some(table) = parsed.get("tools").and_then(|t| t.as_table()) {
            tools.extend(table.keys().cloned());
        }
    }
    tools
}

/// Which hosts installing `stack` and `repo` tools needs. `configured` is the repo's `[egress] tools` from
/// factory.toml (tool to hosts), which the control plane sends in the request: it covers a tool the table doesn't
/// know and takes precedence over it. `mise_missing` adds mise's own installer. A `[stack]` tool with no hosts either
/// way is an error; a repo tool with none is skipped with a warning, since its install is best effort.
/// `repo_config` is whether the checkout has a mise config at all: it needs mise even when none of its tools are known.
pub fn install_hosts_for(
    stack: &[String],
    repo: &[String],
    configured: &BTreeMap<String, Vec<String>>,
    repo_config: bool,
    mise_missing: bool,
) -> Result<Vec<InstallHost>> {
    let known = |tool: &str| -> Option<Vec<String>> {
        configured.get(tool).cloned().or_else(|| hosts_for(tool).map(|h| h.into_iter().map(String::from).collect()))
    };
    let mut asks: Vec<(String, Vec<String>)> = Vec::new();
    for tool in stack {
        let hosts = known(tool).ok_or_else(|| {
            Error::Other(format!(
                "[stack] tool `{tool}` has no known download hosts; list them in factory.toml, e.g. `[egress.tools]` with `{tool} = [\"example.com\"]`"
            ))
        })?;
        asks.push((tool.clone(), hosts));
    }
    for tool in repo.iter().filter(|t| !stack.contains(t)) {
        match known(tool) {
            Some(hosts) => asks.push((tool.clone(), hosts)),
            None => tracing::warn!(
                %tool,
                "the repo's mise.toml asks for a tool with no known download hosts; skipping it unless `[egress.tools]` in factory.toml lists them"
            ),
        }
    }
    if asks.is_empty() && !(repo_config && mise_missing) {
        return Ok(Vec::new());
    }
    // Versions like `22` or `stable` are resolved over the network.
    let strings = |hosts: &[&str]| hosts.iter().map(|h| h.to_string()).collect::<Vec<_>>();
    asks.insert(0, ("mise".into(), strings(MISE_VERSIONS)));
    if mise_missing {
        asks.insert(0, ("mise".into(), strings(&[&["mise.run"], GITHUB].concat())));
    }
    let mut seen = std::collections::BTreeSet::new();
    let mut out = Vec::new();
    for (tool, hosts) in asks {
        for host in hosts {
            if seen.insert(host.clone()) {
                out.push(InstallHost { host, tool: tool.clone() });
            }
        }
    }
    Ok(out)
}

pub struct Mise {
    /// The mise binary; `None` looks for `mise` on PATH, then in `~/.local/bin`, and installs it if missing.
    bin: Option<PathBuf>,
    /// mise's global `conf.d`, where the generated config goes.
    conf_dir: PathBuf,
}

impl Mise {
    pub fn new() -> Mise {
        let home = std::env::var_os("HOME").map(PathBuf::from).unwrap_or_else(|| PathBuf::from("/root"));
        Mise { bin: None, conf_dir: home.join(".config/mise/conf.d") }
    }

    /// For tests: a given binary (never installed) and config directory.
    pub fn with(bin: impl Into<PathBuf>, conf_dir: impl Into<PathBuf>) -> Mise {
        Mise { bin: Some(bin.into()), conf_dir: conf_dir.into() }
    }

    fn generated(&self) -> PathBuf {
        self.conf_dir.join(GENERATED)
    }

    fn repo_config(dir: &Path) -> Option<PathBuf> {
        REPO_CONFIGS.iter().map(|c| dir.join(c)).find(|p| p.exists())
    }

    /// The binary, if there is one.
    fn find(&self) -> Option<PathBuf> {
        if let Some(bin) = &self.bin {
            return Some(bin.clone());
        }
        let local = std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".local/bin/mise"));
        let on_path = std::env::var_os("PATH")
            .into_iter()
            .flat_map(|p| std::env::split_paths(&p).collect::<Vec<_>>())
            .map(|d| d.join("mise"));
        on_path.chain(local).find(|p| p.is_file())
    }

    /// Whether `dir` runs under mise: the factory's tools or the repo's own config ask for it.
    pub fn active(&self, dir: &Path) -> bool {
        self.find().is_some() && (self.generated().exists() || Mise::repo_config(dir).is_some())
    }

    async fn ensure(&self) -> Result<PathBuf> {
        if let Some(bin) = self.find() {
            return Ok(bin);
        }
        let home = std::env::var("HOME").map_err(|_| Error::Other("mise install: HOME is not set".into()))?;
        let target = PathBuf::from(&home).join(".local/bin/mise");
        tracing::info!(target = %target.display(), "installing mise");
        let out = Command::new("sh")
            .arg("-c")
            .arg("curl -fsSL https://mise.run | sh")
            .env("MISE_INSTALL_PATH", &target)
            .stdin(Stdio::null())
            .output()
            .await
            .map_err(|e| Error::Other(format!("mise install: {e}")))?;
        if !out.status.success() || !target.exists() {
            let msg = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
            return Err(Error::Other(format!("couldn't install mise: {}", msg.trim())));
        }
        Ok(target)
    }

    async fn run(bin: &Path, dir: &Path, args: &[&str]) -> Result<String> {
        Mise::exec(bin, dir, args, false).await
    }

    /// For the agent phase, where egress is closed: mise must not try to resolve versions or install.
    async fn run_offline(bin: &Path, dir: &Path, args: &[&str]) -> Result<String> {
        Mise::exec(bin, dir, args, true).await
    }

    async fn exec(bin: &Path, dir: &Path, args: &[&str], offline: bool) -> Result<String> {
        let out = Command::new(bin)
            .args(args)
            .current_dir(dir)
            .env("MISE_YES", "1")
            .env("MISE_OFFLINE", if offline { "1" } else { "0" })
            .stdin(Stdio::null())
            .output()
            .await
            .map_err(|e| Error::Other(format!("mise {}: {e}", args.join(" "))))?;
        let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
        if out.status.success() {
            return Ok(text);
        }
        Err(Error::Other(format!("mise {} failed: {}", args.join(" "), text.trim())))
    }

    /// The hosts installing the factory's `tools` and the checkout's own mise tools at `dir` needs, worked out offline.
    pub async fn install_hosts(
        &self,
        dir: &Path,
        tools: &BTreeMap<String, String>,
        configured: &BTreeMap<String, Vec<String>>,
    ) -> Result<Vec<InstallHost>> {
        let stack: Vec<String> = tools.keys().cloned().collect();
        install_hosts_for(&stack, &repo_tools(dir), configured, Mise::repo_config(dir).is_some(), self.find().is_none())
    }

    /// Installs what the factory's `tools` and the repo's own mise config ask for, in the checkout at `dir`. The repo's
    /// pins win over the factory's tools. Does nothing for a repo with neither.
    pub async fn bootstrap(&self, dir: &Path, tools: &BTreeMap<String, String>) -> Result<()> {
        let repo_config = Mise::repo_config(dir);
        if tools.is_empty() && repo_config.is_none() {
            let _ = tokio::fs::remove_file(self.generated()).await;
            return Ok(());
        }
        let bin = self.ensure().await?;
        if tools.is_empty() {
            let _ = tokio::fs::remove_file(self.generated()).await;
        } else {
            if let Some(path) = &repo_config {
                let text = tokio::fs::read_to_string(path).await.unwrap_or_default();
                let kept = overridden(tools, &text);
                if !kept.is_empty() {
                    tracing::info!(tools = %kept.join(", "), repo_config = %path.display(), "the repo's own mise pins win over [stack]");
                }
            }
            tokio::fs::create_dir_all(&self.conf_dir)
                .await
                .map_err(|e| Error::Other(format!("{}: {e}", self.conf_dir.display())))?;
            tokio::fs::write(self.generated(), render(tools))
                .await
                .map_err(|e| Error::Other(format!("{}: {e}", self.generated().display())))?;
        }
        // The factory's own tools first, from outside the checkout so the repo's config can't fail them: these are what
        // the run needs, and a failure here fails the prepare.
        if !tools.is_empty() {
            let home = self.conf_dir.clone();
            let out = Mise::run(&bin, &home, &["bootstrap", "--only", "tools"]).await?;
            tracing::info!("mise bootstrap of [stack]:\n{}", out.trim());
        }
        if repo_config.is_none() {
            return Ok(());
        }
        // The repo's own config (dev-machine tools and all) is best effort: its failure is logged, not fatal, since
        // `setup` and the checks say plainly if something the repo needed is missing. The checkout is untrusted by
        // default; the factory is the one installing it.
        let _ = Mise::run(&bin, dir, &["trust"]).await;
        match Mise::run(&bin, dir, &["bootstrap", "plan"]).await {
            Ok(plan) => tracing::info!("mise bootstrap plan:\n{}", plan.trim()),
            Err(e) => tracing::warn!(error = %e, "couldn't read the repo's mise bootstrap plan"),
        }
        match Mise::run(&bin, dir, &["bootstrap", "--only", BOOTSTRAP_PARTS]).await {
            Ok(out) => tracing::info!("mise bootstrap of the repo's config:\n{}", out.trim()),
            Err(e) => {
                tracing::warn!(error = %e, "the repo's own mise config didn't fully install; continuing with [stack]")
            }
        }
        Ok(())
    }

    /// The environment mise gives a command in `dir`, with the pinned tools on PATH. Empty when `dir` isn't under mise.
    pub async fn env(&self, dir: &Path) -> BTreeMap<String, String> {
        let Some(bin) = self.find().filter(|_| self.active(dir)) else { return BTreeMap::new() };
        let out = Mise::run_offline(&bin, dir, &["env", "--json"]).await;
        match out.ok().and_then(|o| serde_json::from_str(o.trim()).ok()) {
            Some(env) => env,
            None => {
                tracing::warn!("couldn't read mise's environment; the agent gets the stock tools");
                BTreeMap::new()
            }
        }
    }

    /// `sh -c` for a check: through `mise exec` when `dir` runs under mise.
    pub fn shell(&self, dir: &Path) -> Command {
        match self.find().filter(|_| self.active(dir)) {
            Some(bin) => {
                let mut cmd = Command::new(bin);
                cmd.args(["exec", "--", "sh", "-c"]).env("MISE_YES", "1").env("MISE_OFFLINE", "1");
                cmd
            }
            None => {
                let mut cmd = Command::new("sh");
                cmd.arg("-c");
                cmd
            }
        }
    }
}

impl Default for Mise {
    fn default() -> Mise {
        Mise::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tools(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect()
    }

    #[test]
    fn the_config_lists_the_stack() {
        let config = render(&tools(&[("rust", "stable"), ("node", "22"), ("pnpm", "9")]));
        let parsed = config.parse::<toml::Table>().unwrap();
        let t = parsed["tools"].as_table().unwrap();
        assert_eq!(t["rust"].as_str(), Some("stable"));
        assert_eq!(t["node"].as_str(), Some("22"));
        assert_eq!(t["pnpm"].as_str(), Some("9"));
        assert_eq!(t.len(), 3);
    }

    #[test]
    fn a_repos_own_pins_win() {
        let stack = tools(&[("node", "22"), ("python", "3.12")]);
        let repo = "[tools]\nnode = \"20\"\n\n[tasks.build]\nrun = \"true\"\n";
        assert_eq!(overridden(&stack, repo), vec!["node".to_string()]);
        assert!(overridden(&stack, "").is_empty());
        assert!(overridden(&stack, "not toml [").is_empty());
    }

    fn none() -> BTreeMap<String, Vec<String>> {
        BTreeMap::new()
    }

    fn names(hosts: &[InstallHost]) -> Vec<&str> {
        hosts.iter().map(|h| h.host.as_str()).collect()
    }

    #[test]
    fn a_node_stack_needs_only_nodejs_and_mises_version_lists() {
        let hosts = install_hosts_for(&["node".to_string()], &[], &none(), false, false).unwrap();
        assert_eq!(names(&hosts), ["mise.jdx.dev", "mise-versions.jdx.dev", "nodejs.org"]);
        assert_eq!(hosts.last().unwrap().tool, "node");
    }

    #[test]
    fn mises_installer_hosts_are_opened_only_when_mise_is_missing() {
        let node = ["node".to_string()];
        assert!(!names(&install_hosts_for(&node, &[], &none(), false, false).unwrap()).contains(&"mise.run"));
        let hosts = install_hosts_for(&node, &[], &none(), false, true).unwrap();
        assert!(names(&hosts).contains(&"mise.run"), "{hosts:?}");
        assert!(hosts.iter().any(|h| h.host == "github.com" && h.tool == "mise"));
    }

    #[test]
    fn nothing_to_install_opens_nothing() {
        assert!(install_hosts_for(&[], &[], &none(), false, true).unwrap().is_empty());
    }

    #[test]
    fn a_repo_config_with_no_known_tools_still_opens_mises_installer_when_mise_is_missing() {
        let hosts = install_hosts_for(&[], &[], &none(), true, true).unwrap();
        assert!(names(&hosts).contains(&"mise.run") && names(&hosts).contains(&"github.com"), "{hosts:?}");
        assert!(
            install_hosts_for(&[], &["cargo:ripgrep".to_string()], &none(), true, true).unwrap().len() >= hosts.len()
        );
        assert!(install_hosts_for(&[], &[], &none(), true, false).unwrap().is_empty());
    }

    #[test]
    fn backends_map_to_their_registries() {
        assert_eq!(hosts_for("npm:prettier").unwrap(), ["registry.npmjs.org"]);
        assert_eq!(hosts_for("core:node").unwrap(), ["nodejs.org"]);
        assert_eq!(hosts_for("pipx:black").unwrap(), ["pypi.org", "files.pythonhosted.org"]);
        assert!(hosts_for("aqua:BurntSushi/ripgrep").unwrap().contains(&"github.com"));
        assert!(hosts_for("python").unwrap().contains(&"pypi.org"));
        assert!(hosts_for("zig").is_none());
        assert!(hosts_for("cargo:ripgrep").is_none());
    }

    #[test]
    fn an_unknown_stack_tool_fails_unless_factory_toml_lists_its_hosts() {
        let zig = ["zig".to_string()];
        let err = install_hosts_for(&zig, &[], &none(), false, false).unwrap_err().to_string();
        assert!(err.contains("`zig`") && err.contains("[egress.tools]"), "{err}");
        let configured = BTreeMap::from([("zig".to_string(), vec!["ziglang.org".to_string()])]);
        let hosts = install_hosts_for(&zig, &[], &configured, false, false).unwrap();
        assert!(hosts.iter().any(|h| h.host == "ziglang.org" && h.tool == "zig"), "{hosts:?}");
    }

    #[test]
    fn configured_hosts_cover_a_repo_tool_and_override_the_table() {
        let node = ["node".to_string()];
        let zig = ["zig".to_string(), "python".to_string()];
        let skipped = install_hosts_for(&node, &zig, &none(), true, false).unwrap();
        assert!(names(&skipped).contains(&"pypi.org") && !names(&skipped).contains(&"ziglang.org"));
        let configured = BTreeMap::from([
            ("zig".to_string(), vec!["ziglang.org".to_string()]),
            ("node".to_string(), vec!["mirror.example".to_string()]),
        ]);
        let hosts = install_hosts_for(&node, &zig, &configured, true, false).unwrap();
        assert!(names(&hosts).contains(&"ziglang.org") && names(&hosts).contains(&"mirror.example"));
        assert!(!names(&hosts).contains(&"nodejs.org"));
    }

    #[test]
    fn a_repos_mise_toml_tools_are_read_from_the_checkout() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("mise.toml"), "[tools]\npython = \"3.12\"\n\"npm:prettier\" = \"latest\"\n")
            .unwrap();
        let mut tools = repo_tools(dir.path());
        tools.sort();
        assert_eq!(tools, ["npm:prettier", "python"]);
    }
}
